void kesh_draw_char(uint32_t *fb, int fb_w, char c, int x, int y, uint32_t color) {
    if (!fb || c < 32 || c > 126) return;
    const uint8_t *glyph = font8x8_basic[c - 32];
    for (int r = 0; r < 8; r++) {
        uint8_t row = glyph[r];
        int py = y + r;
        for (int b = 0; b < 8; b++) {
            if (row & (1 << (7 - b))) {
                fb[py * fb_w + (x + b)] = color;
            }
        }
    }
}

void kesh_draw_text(uint32_t *fb, int fb_w, const char *text, int x, int y, uint32_t color) {
    if (!fb || !text) return;
    int cx = x;
    int cy = y;
    while (*text) {
        char c = *text++;
        if (c == '\n') {
            cx = x;
            cy += 12;
            continue;
        }
        kesh_draw_char(fb, fb_w, c, cx, cy, color);
        cx += 8;
    }
}
