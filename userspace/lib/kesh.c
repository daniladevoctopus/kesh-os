void* memcpy(void *dest, const void *src, size_t n) {
    uint8_t *d = (uint8_t*)dest;
    const uint8_t *s = (const uint8_t*)src;
    for (size_t i = 0; i < n; i++) d[i] = s[i];
    return dest;
}

void* memset(void *s, int c, size_t n) {
    uint8_t *p = (uint8_t*)s;
    for (size_t i = 0; i < n; i++) p[i] = (uint8_t)c;
    return s;
}

void kesh_exit(int code) {
    kesh_syscall1(SYS_EXIT, code);
    while (1) { __asm__ volatile ("pause"); }
}

void kesh_clear(uint32_t *fb, int w, int h, uint32_t color) {
    if (!fb) return;
    int total = w * h;
    for (int i = 0; i < total; i++) {
        fb[i] = color;
    }
}

void kesh_draw_rect(uint32_t *fb, int fb_w, int x, int y, int w, int h, uint32_t color) {
    if (!fb || fb_w <= 0) return;
    for (int r = 0; r < h; r++) {
        int py = y + r;
        if (py < 0) continue;
        for (int c = 0; c < w; c++) {
            int px = x + c;
            if (px < 0 || px >= fb_w) continue;
            fb[py * fb_w + px] = color;
        }
    }
}

static inline uint32_t blend_color(uint32_t bg, uint32_t fg, uint8_t alpha) {
    if (alpha == 0) return bg;
    if (alpha == 255) return fg;
    uint32_t inv = 255 - alpha;
    uint32_t r = (((fg >> 16) & 0xFF) * alpha + ((bg >> 16) & 0xFF) * inv) / 255;
    uint32_t g = (((fg >> 8) & 0xFF) * alpha + ((bg >> 8) & 0xFF) * inv) / 255;
    uint32_t b = ((fg & 0xFF) * alpha + (bg & 0xFF) * inv) / 255;
    return (r << 16) | (g << 8) | b;
}

void kesh_draw_rect_alpha(uint32_t *fb, int fb_w, int x, int y, int w, int h, uint32_t color, uint8_t alpha) {
    if (!fb || alpha == 0 || fb_w <= 0) return;
    for (int r = 0; r < h; r++) {
        int py = y + r;
        if (py < 0) continue;
        for (int c = 0; c < w; c++) {
            int px = x + c;
            if (px < 0 || px >= fb_w) continue;
            uint32_t *dst = &fb[py * fb_w + px];
            *dst = blend_color(*dst, color, alpha);
        }
    }
}

void kesh_draw_rounded_rect(uint32_t *fb, int fb_w, int x, int y, int w, int h, int r, uint32_t color) {
    if (!fb || fb_w <= 0) return;
    if (r <= 0) {
        kesh_draw_rect(fb, fb_w, x, y, w, h, color);
        return;
    }
    int r2 = r * r;
    for (int dy = 0; dy < h; dy++) {
        int py = y + dy;
        if (py < 0) continue;
        for (int dx = 0; dx < w; dx++) {
            int px = x + dx;
            if (px < 0 || px >= fb_w) continue;
            int cx = -1, cy = -1;
            if (dx < r && dy < r) { cx = r; cy = r; }
            else if (dx >= w - r && dy < r) { cx = w - r - 1; cy = r; }
            else if (dx < r && dy >= h - r) { cx = r; cy = h - r - 1; }
            else if (dx >= w - r && dy >= h - r) { cx = w - r - 1; cy = h - r - 1; }

            if (cx != -1) {
                int dist2 = (dx - cx) * (dx - cx) + (dy - cy) * (dy - cy);
                if (dist2 > r2) continue;
            }
            fb[py * fb_w + px] = color;
        }
    }
}

